/** Each browser project runs every spec at once on the same servers: this suffix keeps their nicks and channels apart */
export const projectTag = (testInfo: TestInfo): 'cr' | 'ff' => (testInfo.project.name.includes('firefox') ? 'ff' : 'cr');

/** Tests of one spec run at once too: this suffix, unique to one test in one project, keeps their nicks and channels apart */
export const testTag = (testInfo: TestInfo): string => `${projectTag(testInfo)}${testInfo.testId.slice(-5)}`;

/**
 * Wrap `WebSocket` on the page so a test can force every live socket closed,
 * simulating a connection drop (Wi-Fi/cellular handoff, server hiccup) without
 * touching the page itself. Must be called before `page.goto`.
 *
 * Exposes `window.__closeAllWS()` — closes every OPEN/CONNECTING app socket and
 * returns `{ total, closed }`. Same technique the reconnect specs already use
 * inline; shared here so the mobile-reconnect and e2ee-reconnect specs agree on
 * it. Playwright's own `context.setOffline` is avoided on purpose: it doesn't
 * reliably surface a `close` event to the app on every browser.
 */
export const installWebSocketKillSwitch = async (page: Page): Promise<void> => {
  await page.addInitScript(() => {
    const OrigWS = globalThis.WebSocket;
    const allSockets: WebSocket[] = [];

    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    (globalThis as any).WebSocket = function (url: string, protocols?: string | string[]) {
      const ws = protocols ? new OrigWS(url, protocols) : new OrigWS(url);
      // Leave Vite's dev-server sockets alone: once its HMR socket drops, the Vite client reloads the page
      if (![protocols].flat().some((protocol) => protocol === 'vite-hmr' || protocol === 'vite-ping')) {
        allSockets.push(ws);
      }
      return ws;
    };
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    (globalThis as any).WebSocket.prototype = OrigWS.prototype;
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    (globalThis as any).WebSocket.CONNECTING = OrigWS.CONNECTING;
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    (globalThis as any).WebSocket.OPEN = OrigWS.OPEN;
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    (globalThis as any).WebSocket.CLOSING = OrigWS.CLOSING;
    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    (globalThis as any).WebSocket.CLOSED = OrigWS.CLOSED;

    // eslint-disable-next-line @typescript-eslint/no-explicit-any
    (globalThis as any).__closeAllWS = () => {
      let closed = 0;
      for (const ws of allSockets) {
        if (ws.readyState === OrigWS.OPEN || ws.readyState === OrigWS.CONNECTING) {
          ws.close();
          closed++;
        }
      }
      return { total: allSockets.length, closed };
    };
  });
};

/** Force every live WebSocket on the page closed (see `installWebSocketKillSwitch`). */
export const dropConnection = async (page: Page): Promise<void> => {
  // eslint-disable-next-line @typescript-eslint/no-explicit-any
  await page.evaluate(() => (globalThis as any).__closeAllWS());
};

const ERGO_HOST = 'localhost';
// Port 6697 is blocked by Chrome (ERR_UNSAFE_PORT); use 8097 instead
const ERGO_WSS_PORT = '8097';
// The address the gateway dials; the test servers publish their plain ports on IPv4 loopback only
const GATEWAY_IRC_HOST = '127.0.0.1';

/**
 * Serves preview images (YouTube thumbnails, the simpleircclient.com test images) from a local file, so
 * preview tests don't need the internet. The delay keeps every load asynchronous, as on a real network.
 */
export const serveImagePreviews = async (page: Page, delayMs = 300): Promise<void> => {
  const image = readFileSync(new URL('../public/icon-192.png', import.meta.url));
  await page.route(/^https:\/\/(img\.youtube\.com|simpleircclient\.com\/assets)\//, async (route) => {
    await new Promise((resolve) => setTimeout(resolve, delayMs));
    await route.fulfill({ contentType: 'image/png', body: image });
  });
};

/** Waits until the image has loaded, and fails if it cannot: the app swaps an image that fails for its fallback */
export const expectImageLoaded = async (image: Locator): Promise<void> => {
  await expect(image).toBeVisible({ timeout: 10_000 });
  expect(await image.evaluate((element: HTMLImageElement) => element.decode().then(() => true, () => false))).toBe(true);
};

/** Read the random server password generated by global-setup */
export const getServerPassword = (): string => readFileSync(PASSWORD_FILE, 'utf8');

/** How the wizard reaches the project's test server: its plain IRC port through the gateway, otherwise ergo's WebSocket. */
export const testServerAddress = (): { host: string; port: string; type: 'Standard' | 'WebSocket' } => {
  const server = testServer();
  return server.viaGateway
    ? { host: GATEWAY_IRC_HOST, port: String(server.ircPort), type: 'Standard' }
    : { host: ERGO_HOST, port: ERGO_WSS_PORT, type: 'WebSocket' };
};

/** Enter the project's test server as a custom server. */
export const fillTestServer = async (page: Page): Promise<void> => {
  const { host, port, type } = testServerAddress();
  await page.getByLabel('Server address').fill(host);
  await page.getByLabel('Port').clear();
  await page.getByLabel('Port').fill(port);
  await page.getByRole('button', { name: type }).click();
};

/** A custom server asks for a bouncer account first; the test IRC servers are no bouncers */
export const skipBouncerAccount = async (page: Page): Promise<void> => {
  await expect(page.getByRole('heading', { name: 'Bouncer account' })).toBeVisible();
  await page.getByRole('button', { name: 'Skip' }).click();
};

/** How long the wizard waits, once connected, for NickServ to say the nick is registered (WizardLoading) */
const WIZARD_NICKSERV_WAIT_MS = 5_000;

/**
 * Go through the wizard to connect to the project's test server.
 * Enters nick, custom server, server password,
 * and either joins specified channels or skips the channel step.
 */
export const connectViaWizard = async (
  page: Page,
  nick: string,
  options: { channels?: string[] } = {},
): Promise<void> => {
  // The page's clock, so the wizard's wait for NickServ can be passed at once
  await page.clock.install();

  // Step 1: Nick
  await page.getByLabel('Enter your nickname').fill(nick);
  await page.getByRole('button', { name: 'Next' }).click();

  // Step 2: Server
  await fillTestServer(page);

  // Enter server password
  await page.getByLabel('Server password').fill(getServerPassword());

  await page.getByRole('button', { name: 'Next' }).click();
  // Skipping it connects and goes to the loading step
  await skipBouncerAccount(page);

  // Step 3: Loading - wait for connection, then past the password check
  await page.getByText('Connected').waitFor({ timeout: 15_000 });
  await page.clock.fastForward(WIZARD_NICKSERV_WAIT_MS);
  await page.getByText('Select a irc channel').waitFor({ timeout: 15_000 });

  // Step 4: Channels - join or skip
  if (options.channels && options.channels.length > 0) {
    // Wait for channel list to finish loading
    await page.getByText('Downloading channels list').waitFor({ state: 'hidden', timeout: 15_000 });

    // Select each channel by clicking its row. The row's accessible name is
    // "<channel> <users> <topic>", so match it anchored at the start to avoid
    // one channel name being a substring of another (e.g. #settings vs.
    // #chan-settings).
    for (const channel of options.channels) {
      const escaped = channel.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
      await page.getByRole('button', { name: new RegExp(`^${escaped}(\\s|$)`) }).click();
    }
    await page.getByRole('button', { name: 'Next' }).click();
  } else {
    await page.getByRole('button', { name: 'Skip' }).click();
  }

  // Wait for main page to render
  await page.locator('#message-input').waitFor({ timeout: 10_000 });
};

