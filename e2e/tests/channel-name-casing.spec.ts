import { test, expect, type Page } from '@playwright/test';
import { createIrcClient, type IrcClient } from '../irc-client';
import { connectViaWizard, readPersistedNetwork, testTag, writeIdbKey } from '../helpers';
import { testServer } from '../test-server';

/**
 * A channel is one channel however it is cased. Reported by a user: their
 * sidebar held two "#religie" entries - one collecting only the system
 * messages, the other the actual chat - and removing either left the other
 * behind. The client held the casing the user typed (or restored from storage)
 * while the server answered with its own canonical one, and the two never met.
 *
 * Ergo canonicalises channel names on everything it relays, so there the
 * mismatch is seeded through the persisted store, which is where affected users
 * carry it in from. ngircd answers a JOIN in the casing it was sent but relays
 * chat in whatever casing the sender used, so there it also comes from the wire.
 */

/** The casing the bot creates the channel with - what the server will echo */
let serverCasing: string;
/** The casing the user typed */
let userCasing: string;
let nick: string;
/** The casing the server's reply to our JOIN carries, which names the window */
const joinedCasing = (): string => (testServer().name === 'ergo' ? serverCasing : userCasing);
/** The channel in any casing */
const anyCasing = (): RegExp => new RegExp(`^${userCasing}$`, 'i');

/** Overwrite the persisted channel store, as a build without the fix left it */
const seedChannelStore = async (page: Page, state: unknown, version: number): Promise<void> => {
  const network = await readPersistedNetwork(page);
  if (network === undefined) {
    throw new Error('no network in sic-networks - the wizard did not complete');
  }
  await writeIdbKey(page, `sic-channels:${network.networkId}`, JSON.stringify({ state, version }));
};

const persistedChannel = (name: string, messages: { id: string; text: string; time: string }[] = []) => ({
  name,
  category: 'channel',
  unReadMessages: 0,
  messages: messages.map((message) => ({
    id: message.id,
    message: message.text,
    target: name,
    time: message.time,
    category: 'info',
  })),
  topic: '',
  topicSetBy: '',
  topicSetTime: 0,
  typing: [],
});

let bot: IrcClient;
let page: Page;

/** Leaves the app, which writes out what it holds as it goes, and opens it again on this channel store */
const reopenWithChannelStore = async (state: unknown, version: number): Promise<void> => {
  // A page of the app's origin without the app, so nothing writes over the seeded store
  await page.goto('/favicon.ico');
  await seedChannelStore(page, state, version);
  await page.goto('/');
};

const joinInUserCasing = async (): Promise<void> => {
  await page.locator('#message-input').fill(`/join ${userCasing}`);
  await page.locator('#message-input').press('Enter');
  await expect(page.getByTestId('channels-sidebar').getByRole('button', { name: joinedCasing(), exact: true })).toBeVisible({ timeout: 10_000 });
};

test.beforeEach(async ({ page: testPage }, testInfo) => {
  page = testPage;
  const tag = testTag(testInfo);
  serverCasing = `#CasingTest-${tag}`;
  userCasing = `#casingtest-${tag}`;
  nick = `casing-tester-${tag}`;

  bot = await createIrcClient(`casingbot-${tag}`);
  await bot.join(serverCasing);
  await bot.setTopic(serverCasing, 'One channel, one window');

  await page.goto('/');
  await connectViaWizard(page, nick);
});

test.afterEach(() => {
  bot.disconnect();
});

test.describe('Channel name casing', () => {
  test('joining in another casing opens one window under the server name', async () => {
    const channelNav = page.getByTestId('channels-sidebar');

    // The server's casing wins in the UI...
    await joinInUserCasing();

    // ...and there is exactly one entry, not one per casing
    await expect(channelNav.getByRole('button', { name: anyCasing() })).toHaveCount(1);
  });

  test('chat and system messages land in the same window', async () => {
    const channelNav = page.getByTestId('channels-sidebar');
    await joinInUserCasing();
    await channelNav.getByRole('button', { name: joinedCasing(), exact: true }).click();

    // The join notice is generated by the client, the chat comes from the
    // server - the bug put these two in separate windows
    await expect(page.getByText(nick).first()).toBeVisible({ timeout: 10_000 });

    bot.sendMessage(serverCasing, 'chat lands here');
    await expect(page.getByText('chat lands here')).toBeVisible({ timeout: 10_000 });

    await expect(page.getByTestId('topic-display')).toHaveText('One channel, one window', { timeout: 10_000 });
    await expect(channelNav.getByRole('button', { name: anyCasing() })).toHaveCount(1);
  });

  test('removing the channel removes it for good', async () => {
    const channelNav = page.getByTestId('channels-sidebar');
    await joinInUserCasing();

    await channelNav.getByRole('button', { name: joinedCasing(), exact: true }).hover();
    await channelNav.getByRole('button', { name: `Leave ${joinedCasing()}` }).click();

    // No leftover under any casing
    await expect(channelNav.getByRole('button', { name: anyCasing() })).toHaveCount(0);
    await expect(page.locator('#message-input')).not.toHaveAttribute('placeholder', new RegExp(userCasing, 'i'));
  });

  test('case-duplicate windows left by older versions are merged on load', async () => {
    const channelNav = page.getByTestId('channels-sidebar');

    // Exactly what an affected user has in storage: the same channel twice,
    // one window holding the system messages and the other the chat, written
    // under the pre-fix schema version
    await reopenWithChannelStore({
      openChannels: [
        persistedChannel('#seeded', [{ id: 'sys-1', text: 'seeded system message', time: '2026-07-30T10:00:00.000Z' }]),
        persistedChannel('#Seeded', [{ id: 'chat-1', text: 'seeded chat message', time: '2026-07-30T11:00:00.000Z' }]),
      ],
      openChannelsShortList: [
        { name: '#seeded', category: 'channel', unReadMessages: 0 },
        { name: '#Seeded', category: 'channel', unReadMessages: 0 },
      ],
    }, 1);

    // One window, under the name of the first of the two
    await expect(channelNav.getByRole('button', { name: /^#seeded$/i })).toHaveCount(1, { timeout: 10_000 });

    // ...holding what had been split across both
    await channelNav.getByRole('button', { name: '#seeded', exact: true }).click();
    await expect(page.getByText('seeded system message')).toBeVisible({ timeout: 10_000 });
    await expect(page.getByText('seeded chat message')).toBeVisible({ timeout: 10_000 });
  });

  test('a window restored under a stale casing is adopted, not duplicated', async () => {
    const channelNav = page.getByTestId('channels-sidebar');

    // A single window under the casing the user typed. On reconnect the client
    // rejoins it and the server answers with its own casing - which used to
    // open a second window that then only ever received the system broadcasts.
    await reopenWithChannelStore({
      openChannels: [persistedChannel(userCasing)],
      openChannelsShortList: [{ name: userCasing, category: 'channel', unReadMessages: 0 }],
    }, 1);

    await expect(channelNav.getByRole('button', { name: anyCasing() })).toHaveCount(1, { timeout: 10_000 });

    // Reconnect so the client rejoins the channel from the restored list
    await page.getByRole('button', { name: 'Connect' }).click();

    // The server's casing is adopted by the window we already had
    await expect(channelNav.getByRole('button', { name: joinedCasing(), exact: true })).toBeVisible({ timeout: 20_000 });
    await expect(channelNav.getByRole('button', { name: anyCasing() })).toHaveCount(1);

    // ...and it is the live window: the topic and new chat arrive in it
    await channelNav.getByRole('button', { name: joinedCasing(), exact: true }).click();
    await expect(page.getByTestId('topic-display')).toHaveText('One channel, one window', { timeout: 10_000 });

    bot.sendMessage(serverCasing, 'after the rejoin');
    await expect(page.getByText('after the rejoin')).toBeVisible({ timeout: 10_000 });
  });
});
